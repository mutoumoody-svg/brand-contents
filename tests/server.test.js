const { test } = require('node:test');
const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
test('服务器启动、静态白名单和登录保护', async t => {
  const data = fs.mkdtempSync(path.join(os.tmpdir(),'brand-test-'));
  const child = spawn(process.execPath,['server.js'], {cwd:path.join(__dirname,'..'),env:{...process.env,PORT:'0',DATA_DIR:data,JWT_SECRET:'',CLAUDE_WORKER_SECRET:'',NODE_ENV:'production',LOCAL_PREVIEW_AUTH_BYPASS:'1'},stdio:['ignore','pipe','pipe']});
  let stderr='';child.stderr.on('data',d=>{stderr+=d;});
  t.after(async()=>{if(child.exitCode===null){child.kill();await new Promise(r=>child.once('exit',r));}fs.rmSync(data,{recursive:true,force:true});});
  const port=await new Promise((resolve,reject)=>{
    const timer=setTimeout(()=>reject(new Error('启动超时 '+stderr)),15000);
    child.once('exit',code=>{clearTimeout(timer);reject(new Error('启动失败 '+code+' '+stderr));});
    child.stdout.on('data',d=>{const m=String(d).match(/localhost:(\d+)/);if(m){clearTimeout(timer);resolve(m[1]);}});
  });
  const base=`http://127.0.0.1:${port}`;
  assert.equal((await fetch(base+'/api/health')).status,200);
  assert.equal((await fetch(base+'/api/local-preview/session',{method:'POST',headers:{Origin:base,'X-Local-Preview':'1'}})).status,404);
  assert.match(await(await fetch(base+'/')).text(),/文案工坊/);
  for(const p of ['/server.js','/data/users.db','/brand.env','.env','/package.json','/scripts/deploy.sh'])assert.equal((await fetch(base+(p.startsWith('/')?p:'/'+p))).status,404,p);
  assert.equal((await fetch(base+'/workspace.html')).status,200);
  assert.equal((await fetch(base+'/assets/workspace.js')).status,200);
  assert.equal((await fetch(base+'/api/writing/jobs')).status,401);
  const post = (route, body) => fetch(base+route,{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});
  assert.equal((await post('/api/auth/register',{email:'upload-test@example.test',password:'test-only-password',name:'Upload Test'})).status,200);
  const login=await post('/api/auth/login',{email:'upload-test@example.test',password:'test-only-password'});
  assert.equal(login.status,200);
  const {token}=await login.json();
  const testDb=new(require('better-sqlite3'))(path.join(data,'users.db'));
  testDb.prepare('UPDATE users SET auth_version=auth_version+1 WHERE email=?').run('upload-test@example.test');
  assert.equal((await fetch(base+'/api/auth/verify',{headers:{Authorization:'Bearer '+token}})).status,401);
  testDb.prepare('UPDATE users SET auth_version=auth_version-1 WHERE email=?').run('upload-test@example.test');testDb.close();
  const upload=async(name,buffer,type) => {
    const form=new FormData();form.append('file',new Blob([buffer],{type}),name);
    const res=await fetch(base+'/api/brands/parse-file',{method:'POST',headers:{Authorization:'Bearer '+token},body:form});
    return {status:res.status,data:await res.json()};
  };
  const txt=await upload('brand.txt','Brand facts: coffee cup.','text/plain');
  assert.equal(txt.status,200);assert.match(txt.data.text,/Brand facts/);
  const JSZip=require('jszip');
  const docx=new JSZip();
  docx.file('[Content_Types].xml','<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="xml" ContentType="application/xml"/><Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/></Types>');
  docx.file('_rels/.rels','<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/></Relationships>');
  docx.file('word/document.xml','<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body><w:p><w:r><w:t>Verified Word brand facts</w:t></w:r></w:p></w:body></w:document>');
  const word=await upload('brand.docx',await docx.generateAsync({type:'nodebuffer'}),'application/vnd.openxmlformats-officedocument.wordprocessingml.document');
  assert.equal(word.status,200);assert.match(word.data.text,/Verified Word brand facts/);
  const ppt=new JSZip();ppt.file('ppt/slides/slide1.xml','<p:sld xmlns:p="p" xmlns:a="a"><a:t>Verified slide facts</a:t></p:sld>');
  const slide=await upload('brand.pptx',await ppt.generateAsync({type:'nodebuffer'}),'application/vnd.openxmlformats-officedocument.presentationml.presentation');
  assert.equal(slide.status,200);assert.match(slide.data.text,/Verified slide facts/);
  assert.equal((await upload('unsupported.bin','test','application/octet-stream')).status,400);
  assert.equal((await upload('big.txt',Buffer.alloc(21*1024*1024,65),'text/plain')).status,413);
  assert.equal((await fetch(base+'/api/health')).status,200);
});
